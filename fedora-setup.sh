# Print the first asset URL of the latest GitHub release matching a jq regex (empty on any failure)
github_asset_url() {
    local repo="$1"
    local regex="$2"
    curl -fsSL "${CURL_SMALL[@]}" "https://api.github.com/repos/$repo/releases/latest" 2>> "$LOG_FILE" | \
        jq -r --arg re "$regex" '[.assets[]?.browser_download_url | select(test($re))][0] // empty' 2>> "$LOG_FILE" || true
}

# Download a file into the current directory unless it is already there, then remove
# older versions matching old_glob. The download goes to a .part file first, so an
# interrupted download never ends up under the final name. curl rather than wget:
# Fedora's wget2 shows no progress with -q --show-progress and waits forever on a
# stalled connection.
fetch_package() {
    local name="$1"
    local url="$2"
    local file="$3"
    local old_glob="$4"

    if [[ -z "$url" ]] || [[ -z "$file" ]]; then
        log_error "$name download URL not found"
        return 0
    fi

    if [[ -f "$file" ]]; then
        log "$name already downloaded"
        return 0
    fi

    log "Downloading $name..."
    if curl -fL --progress-bar "${CURL_DOWNLOAD[@]}" -o "$file.part" "$url"; then
        mv -f "$file.part" "$file"
        find . -maxdepth 1 -name "$old_glob" ! -name "$file" -delete
        echo "$name downloaded: $file" >> "$LOG_FILE"
    else
        rm -f "$file.part"
        log_error "Failed to download $name"
    fi
}

download_third_party_apps() {
    log_section "Downloading third-party applications"

    mkdir -p "$PACKAGES_DIR"
    pushd "$PACKAGES_DIR" >/dev/null

    local url

    # Ledger Live: the "latest" URL redirects to the versioned AppImage. Read the redirect
    # target without following it (following would download the whole ~200 MB file;
    # the server supports neither HEAD nor range requests)
    log "Checking for Ledger Live updates..."
    url=$(curl -sS "${CURL_SMALL[@]}" -o /dev/null -w '%{redirect_url}' "https://download.live.ledger.com/latest/linux" 2>> "$LOG_FILE" || true)
    if [[ "$url" != *.AppImage ]]; then
        url=""
    fi
    fetch_package "Ledger Live" "$url" "${url##*/}" "ledger-live-desktop-*.AppImage"

    # Telegram Desktop
    log "Checking for Telegram Desktop updates..."
    url=$(github_asset_url "telegramdesktop/tdesktop" 'td-setup-linux-x64-[0-9.]+\.tar\.xz$')
    fetch_package "Telegram Desktop" "$url" "${url##*/}" "td-setup-linux-x64-*.tar.xz"

    # MikroTik WinBox (URL is scraped from the download page; the file is renamed
    # to include the version, since the upstream name is always WinBox_Linux.zip)
    log "Checking for WinBox updates..."
    url=$(curl -fsSL "${CURL_SMALL[@]}" "https://mikrotik.com/download/winbox" 2>> "$LOG_FILE" | \
        grep -Eo 'https://[a-z]+\.mikrotik\.com/routeros/winbox/[^"]+/WinBox_Linux\.zip' | head -n 1 || true)
    if [[ -n "$url" ]]; then
        local winbox_version
        winbox_version=$(awk -F'/' '{print $(NF-1)}' <<< "$url")
        fetch_package "WinBox" "$url" "winbox_${winbox_version}.zip" "winbox_*.zip"
    else
        log_error "WinBox URL not found — MikroTik page format may have changed"
    fi

    echo ""
    log_success "Third-party applications downloaded"
    popd >/dev/null
}

# Check whether an app directory was already extracted from this archive
# (the archive name is recorded in a marker file inside the app directory)
is_installed_from() {
    local app_dir="$1"
    local archive="$2"
    [[ -f "$app_dir/.installed-from" ]] && [[ "$(< "$app_dir/.installed-from")" == "$archive" ]]
}

install_third_party_apps() {
    log_section "Installing third-party applications"
    
    pushd "$PACKAGES_DIR" >/dev/null
    mkdir -p "$APPS_DIR"
    
    # Ledger Live: AppImage under a stable name, icon extracted from the AppImage
    local ledger_appimages=(./ledger-live-desktop-*.AppImage)
    if [[ "${ledger_appimages[0]}" != "./ledger-live-desktop-*.AppImage" ]]; then
        local ledger_target="$APPS_DIR/ledger-live-desktop.AppImage"
        local ledger_icon="$APPS_DIR/ledger-live-desktop.png"

        if [[ -f "$ledger_target" ]] && cmp -s "${ledger_appimages[0]}" "$ledger_target"; then
            log_success "Ledger Live already up to date"
        elif pgrep -f "$ledger_target" >/dev/null 2>&1; then
            log_warning "Ledger Live is running, skipping update (close it and re-run the script)"
        elif install -m0755 "${ledger_appimages[0]}" "$ledger_target" 2>> "$LOG_FILE"; then
            rm -f "$ledger_icon"
            log_success "Ledger Live installed to $ledger_target"
        else
            log_error "Failed to install Ledger Live"
        fi

        if [[ -x "$ledger_target" ]]; then
            if [[ ! -f "$ledger_icon" ]]; then
                local temp_dir
                temp_dir="$(mktemp -d)"
                TEMP_FILES+=("$temp_dir")
                # The top-level icon is a symlink into usr/share/icons, so extract the real files
                (cd "$temp_dir" && "$ledger_target" --appimage-extract 'usr/share/icons/*') >/dev/null 2>&1 || true
                # Prefer a 256x256 icon; don't depend on its file name (the app was renamed
                # to "Ledger Wallet", so the icon name may change too)
                local icons_root="$temp_dir/squashfs-root/usr/share/icons"
                local icon_src
                icon_src="$(find "$icons_root" -type f -path '*/256x256/apps/*.png' 2>/dev/null | head -n 1 || true)"
                if [[ -z "$icon_src" ]]; then
                    icon_src="$(find "$icons_root" -type f -name '*.png' 2>/dev/null | head -n 1 || true)"
                fi
                if [[ -n "$icon_src" ]] && [[ -f "$icon_src" ]]; then
                    cp "$icon_src" "$ledger_icon"
                else
                    log_warning "Could not extract Ledger Live icon"
                fi
            fi
            # Electron AppImages cannot use the SUID sandbox, hence --no-sandbox
            create_desktop_entry "ledger-live-desktop" "Ledger Live" \
                "\"$ledger_target\" --no-sandbox %U" "$ledger_icon" "Office;Finance;" \
                "MimeType=x-scheme-handler/ledgerlive;"
        fi
    fi

    # Telegram (creates its own desktop entry on first launch)
    local tg_archives=(./td-setup-linux-x64-*.tar.xz)
    if [[ "${tg_archives[0]}" != "./td-setup-linux-x64-*.tar.xz" ]]; then
        local tg_archive="${tg_archives[0]#./}"
        local tg_dir="$APPS_DIR/Telegram"

        if is_installed_from "$tg_dir" "$tg_archive"; then
            log_success "Telegram Desktop already up to date"
        elif pgrep -f "$tg_dir/Telegram" >/dev/null 2>&1; then
            log_warning "Telegram Desktop is running, skipping update (close it and re-run the script)"
        else
            log "Extracting Telegram Desktop..."
            if replace_app_dir "$tg_dir" "$tg_archive" tar -xJf "$tg_archive" -C; then
                log_success "Telegram installed to $tg_dir"
            else
                log_error "Failed to extract Telegram (previous version kept)"
            fi
        fi
    fi
    
    # WinBox
    local winbox_zips=(./winbox_*.zip)
    if [[ "${winbox_zips[0]}" != "./winbox_*.zip" ]]; then
        local winbox_zip="${winbox_zips[0]#./}"
        local winbox_dir="$APPS_DIR/WinBox"

        if is_installed_from "$winbox_dir" "$winbox_zip"; then
            log_success "WinBox already up to date"
        elif pgrep -f "$winbox_dir/WinBox" >/dev/null 2>&1; then
            log_warning "WinBox is running, skipping update (close it and re-run the script)"
        else
            log "Extracting WinBox..."
            if replace_app_dir "$winbox_dir" "$winbox_zip" extract_winbox_zip "$winbox_zip"; then
                if [[ -f "$winbox_dir/WinBox" ]]; then
                    chmod +x "$winbox_dir/WinBox"
                fi
                log_success "WinBox installed to $winbox_dir"
            else
                log_error "Failed to extract WinBox (previous version kept)"
            fi
        fi

        if [[ -x "$winbox_dir/WinBox" ]]; then
            create_desktop_entry "winbox" "WinBox" "\"$winbox_dir/WinBox\"" \
                "$winbox_dir/assets/img/winbox.png" "Network;"
        fi
    fi
    
    popd >/dev/null
}

