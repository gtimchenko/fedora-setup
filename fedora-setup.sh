# ============================================================================
# Utility Functions
# ============================================================================

log() {
    echo "[$(date +'%Y-%m-%d %H:%M:%S')] $*" | tee -a "$LOG_FILE"
}

log_blank() {
    echo "" | tee -a "$LOG_FILE"
}

log_error() {
    echo "[$(date +'%Y-%m-%d %H:%M:%S')] ERROR: $*" | tee -a "$LOG_FILE" >&2
    PROBLEMS+=("ERROR: $*")
}

log_success() {
    echo "[$(date +'%Y-%m-%d %H:%M:%S')] ✓ $*" | tee -a "$LOG_FILE"
}

# Colored output on the terminal, plain text in the log file
log_colored() {
    local color="$1"
    shift
    local msg
    msg="[$(date +'%Y-%m-%d %H:%M:%S')] $*"
    printf '\033[%sm%s\033[0m\n' "$color" "$msg"
    echo "$msg" >> "$LOG_FILE"
}

log_warning() {
    log_colored "1;33" "⚠ $*"
    PROBLEMS+=("WARNING: $*")
}

log_critical() {
    log_colored "1;31" "✗ $*"
}

log_section() {
    echo "" | tee -a "$LOG_FILE"
    echo "========================================" | tee -a "$LOG_FILE"
    echo "$*" | tee -a "$LOG_FILE"
    echo "========================================" | tee -a "$LOG_FILE"
}

command_exists() {
    command -v "$1" >/dev/null 2>&1
}

# dnf with --skip-unavailable exits successfully even when it skips packages:
# report the requested packages that are still not installed. --whatprovides is
# needed because some names are provided by differently named packages
# (wget -> wget2-wget, liberation-fonts -> liberation-fonts-all)
report_missing_packages() {
    local missing=()
    local pkg
    for pkg in "$@"; do
        if ! rpm -q --whatprovides "$pkg" >/dev/null 2>&1; then
            missing+=("$pkg")
        fi
    done
    if [[ ${#missing[@]} -gt 0 ]]; then
        log_warning "Not installed (unavailable or failed): ${missing[*]}"
    fi
}

# Replace an app directory with a freshly extracted copy. Extraction goes to a staging
# directory first, so the working copy is kept if extraction fails.
# Usage: replace_app_dir <app_dir> <archive_name> <extract command...>
# The extract command gets the staging directory as its last argument and must
# create <staging>/<basename of app_dir> in it.
replace_app_dir() {
    local app_dir="$1"
    local archive="$2"
    shift 2

    local name
    name="$(basename "$app_dir")"
    local staging
    staging="$(mktemp -d "$(dirname "$app_dir")/.staging.XXXXXX")"
    TEMP_FILES+=("$staging")

    if "$@" "$staging" 2>> "$LOG_FILE" && [[ -d "$staging/$name" ]]; then
        rm -rf "$app_dir"
        if mv "$staging/$name" "$app_dir"; then
            echo "$archive" > "$app_dir/.installed-from"
            rm -rf "$staging"
            return 0
        fi
    fi
    rm -rf "$staging"
    return 1
}

# Extract the WinBox zip (it has no top-level directory) into <dest>/WinBox
extract_winbox_zip() {
    local zip="$1"
    local dest="$2"
    mkdir -p "$dest/WinBox" && unzip -oq "$zip" -d "$dest/WinBox"
}

# Create a desktop entry so an app installed outside the package manager
# shows up in the GNOME app grid
create_desktop_entry() {
    local id="$1"
    local name="$2"
    local exec_line="$3"
    local icon="$4"
    local categories="$5"
    local extra="${6:-}"

    mkdir -p "$DESKTOP_ENTRIES_DIR"
    {
        echo "[Desktop Entry]"
        echo "Type=Application"
        echo "Name=$name"
        echo "Exec=$exec_line"
        echo "Icon=$icon"
        echo "Terminal=false"
        echo "Categories=$categories"
        if [[ -n "$extra" ]]; then
            echo "$extra"
        fi
    } > "$DESKTOP_ENTRIES_DIR/$id.desktop"

    if command_exists update-desktop-database; then
        update-desktop-database "$DESKTOP_ENTRIES_DIR" >/dev/null 2>&1 || true
    fi
    log_success "Desktop entry created for $name"
}

check_fedora() {
    if [[ ! -f /etc/fedora-release ]]; then
        log_error "This script is designed for Fedora. Exiting."
        exit 1
    fi
}

check_not_root() {
    if [[ $EUID -eq 0 ]]; then
        log_error "Do not run this script as root or via sudo; run it as your regular user. Exiting."
        exit 1
    fi
}

# Ask for the sudo password once and keep the timestamp fresh until the script exits
start_sudo_keepalive() {
    if ! sudo -v; then
        log_error "sudo access is required. Exiting."
        exit 1
    fi
    while true; do
        sudo -n true 2>/dev/null || exit
        sleep 60
        kill -0 "$$" 2>/dev/null || exit
    done &
    SUDO_KEEPALIVE_PID=$!
}

initial_system_update() {
    log_section "Performing initial system update"

    echo ""
    log "Updating system packages (this may take a while)..."
    echo ""
    
    # Perform system update
    if sudo dnf -y upgrade --refresh; then
        echo "Initial system update completed successfully" >> "$LOG_FILE"
        echo ""
        log_success "System updated successfully"
    else
        echo "Initial system update completed with some errors" >> "$LOG_FILE"
        echo ""
        log_warning "Some packages failed to update (continuing anyway)"
    fi
    
    # Check if reboot is required
    echo ""
    log "Checking if reboot is required..."
    
    local needs_reboot=false

    # dnf5 needs-restarting (dnf5-plugins) checks kernel, glibc, systemd and other core packages.
    # Run it as root: root's metadata cache is fresh after the upgrade above. Exit code 1 is
    # returned both for "reboot required" and for errors, so the output is checked too.
    local nr_output=""
    local nr_status=0
    nr_output="$(sudo dnf needs-restarting -r 2>&1)" || nr_status=$?
    echo "$nr_output" >> "$LOG_FILE"

    if [[ $nr_status -eq 0 ]]; then
        log_success "No reboot required by dnf needs-restarting"
    elif [[ "$nr_output" == *"Reboot is required"* ]]; then
        log_warning "Reboot required according to dnf needs-restarting"
        needs_reboot=true
    else
        log_warning "dnf needs-restarting failed, falling back to kernel version check"
        # Fallback: compare the running kernel with the newest installed one
        local latest_kernel
        latest_kernel="$(rpm -q --last kernel-core 2>/dev/null | awk 'NR == 1 {sub(/^kernel-core-/, "", $1); print $1}' || true)"
        if [[ -n "$latest_kernel" ]] && [[ "$(uname -r)" != "$latest_kernel" ]]; then
            log_warning "Kernel has been updated"
            needs_reboot=true
        fi
    fi

    if [[ "$needs_reboot" == "true" ]]; then
        # ASCII-only text inside the box: printf pads by bytes, so this keeps the frame aligned
        local border
        border="$(printf '═%.0s' {1..60})"
        echo ""
        log_critical "╔${border}╗"
        local text
        for text in "" "REBOOT REQUIRED" "" \
                    "Critical system packages have been updated." \
                    "Please reboot your system and run this script again." \
                    "" "Run: sudo reboot" ""; do
            log_critical "$(printf '║  %-58s║' "$text")"
        done
        log_critical "╚${border}╝"
        echo ""
        exit 0
    else
        log_success "No reboot required, continuing with setup..."
    fi
}

check_gnome() {
    if [[ "${XDG_CURRENT_DESKTOP:-}" == *"GNOME"* ]] || pgrep -x "gnome-shell" >/dev/null 2>&1; then
        log_success "GNOME desktop detected"
    elif rpm -q gnome-shell >/dev/null 2>&1; then
        # Installed but not running here (e.g. SSH or TTY): GNOME settings may not apply
        log_warning "GNOME is installed but no GNOME session detected; run the script from a GNOME session for full setup"
    else
        log_error "This script supports only Fedora Workstation with GNOME. Exiting."
        exit 1
    fi
}

