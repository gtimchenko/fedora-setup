# Remove Powerlevel10k leftovers (instant prompt, ~/.p10k.zsh sourcing) from a zshrc
remove_p10k_from_zshrc() {
    local zshrc="$1"
    sed -i \
        -e '/^if \[\[ -r .*p10k-instant-prompt-/{N;N;/\nfi$/d}' \
        -e '/^[[:space:]]*\[\[ ! -f ~\/\.p10k\.zsh \]\] || source ~\/\.p10k\.zsh[[:space:]]*$/d' \
        -e '/^# Enable Powerlevel10k instant prompt/d' \
        -e '/^# Initialization code that may require console input/d' \
        -e '/^# confirmations, etc\.) must go above this block/d' \
        -e '/^# Powerlevel10k instant prompt/d' \
        -e '/^# .*p10k configure/d' \
        "$zshrc"
}

setup_zsh() {
    log_section "Setting up Zsh with Oh My Zsh and Starship"

    if ! command_exists zsh; then
        log_error "Zsh not installed, skipping shell setup"
        return 0
    fi

    local omz_dir="$HOME/.oh-my-zsh"
    local zshrc="$HOME/.zshrc"

    # Oh My Zsh (cloned directly: the official installer would also replace ~/.zshrc and run chsh)
    if [[ -f "$omz_dir/oh-my-zsh.sh" ]]; then
        log_success "Oh My Zsh already installed"
    else
        log "Installing Oh My Zsh..."
        if git clone --depth=1 https://github.com/ohmyzsh/ohmyzsh.git "$omz_dir" >> "$LOG_FILE" 2>&1; then
            log_success "Oh My Zsh installed"
        else
            log_error "Failed to install Oh My Zsh"
        fi
    fi

    # ~/.zshrc: a config without Oh My Zsh is moved aside (like the Oh My Zsh installer does)
    if [[ -f "$zshrc" ]] && ! grep -q 'oh-my-zsh.sh' "$zshrc"; then
        mv "$zshrc" "$zshrc.pre-oh-my-zsh"
        log_warning "Existing ~/.zshrc moved to ~/.zshrc.pre-oh-my-zsh"
    fi

    if [[ ! -f "$zshrc" ]]; then
        log "Creating Zsh configuration..."
        cat > "$zshrc" <<'ZSHEOF'
# PATH (typeset -U drops duplicates in nested shells)
typeset -U path PATH
[[ -d "$HOME/.local/bin" ]] && export PATH="$HOME/.local/bin:$PATH"
[[ -d "$HOME/bin" ]] && export PATH="$HOME/bin:$PATH"
[[ -d "$HOME/Applications" ]] && export PATH="$HOME/Applications:$PATH"
[[ -d "$HOME/.cargo/bin" ]] && export PATH="$HOME/.cargo/bin:$PATH"

# Oh My Zsh (no theme: the prompt is provided by Starship)
export ZSH="$HOME/.oh-my-zsh"
ZSH_THEME=""
plugins=(git)
[[ -r $ZSH/oh-my-zsh.sh ]] && source $ZSH/oh-my-zsh.sh

# Starship prompt
if (( $+commands[starship] )); then
    eval "$(starship init zsh)"
fi

# Modern CLI replacements
if (( $+commands[eza] )); then
    alias ls='eza --icons --group-directories-first'
    alias ll='eza -l --icons --group-directories-first --git'
    alias la='eza -la --icons --group-directories-first --git'
    alias lt='eza -T --icons --group-directories-first --level=2'
fi

if (( $+commands[bat] )); then
    alias cat='bat --style=auto'
    export MANPAGER="sh -c 'col -bx | bat -l man -p'"
fi
ZSHEOF
        log_success "Zsh configuration created"
    else
        # Migrate an existing Oh My Zsh config to Starship (a backup is made before any change)
        local needs_theme_reset=false
        local needs_p10k_cleanup=false
        local needs_alias_update=false
        local needs_starship_init=false

        if grep -q '^ZSH_THEME=' "$zshrc" && ! grep -q '^ZSH_THEME=""' "$zshrc"; then
            needs_theme_reset=true
        fi
        if grep -q -e 'p10k-instant-prompt' -e '\.p10k\.zsh' "$zshrc"; then
            needs_p10k_cleanup=true
        fi
        # Update alias generated by an older version of this script (a user's own alias is kept)
        if grep -q "^${ZSH_UPDATE_ALIAS_PREFIX}" "$zshrc" && ! grep -qxF "$ZSH_UPDATE_ALIAS" "$zshrc"; then
            needs_alias_update=true
        fi
        if ! grep -q 'starship init zsh' "$zshrc"; then
            needs_starship_init=true
        fi

        if [[ "$needs_theme_reset" == "true" || "$needs_p10k_cleanup" == "true" || \
              "$needs_alias_update" == "true" || "$needs_starship_init" == "true" ]]; then
            local backup
            backup="$zshrc.bak-$(date +%Y%m%d-%H%M%S)"
            cp "$zshrc" "$backup"
            log "Backed up ~/.zshrc to $backup"
        fi

        if [[ "$needs_theme_reset" == "true" ]]; then
            sed -i 's|^ZSH_THEME=.*|ZSH_THEME=""|' "$zshrc"
            log_success "Oh My Zsh theme disabled (prompt is provided by Starship)"
        fi

        if [[ "$needs_p10k_cleanup" == "true" ]]; then
            remove_p10k_from_zshrc "$zshrc"
            log_success "Powerlevel10k configuration removed from ~/.zshrc"
        fi

        if [[ "$needs_alias_update" == "true" ]]; then
            local updated
            updated="$(awk -v prefix="$ZSH_UPDATE_ALIAS_PREFIX" -v new="$ZSH_UPDATE_ALIAS" \
                'index($0, prefix) == 1 {print new; next} {print}' "$zshrc")"
            printf '%s\n' "$updated" > "$zshrc"
            log_success "Update alias in ~/.zshrc replaced with the current version"
        fi

        if [[ "$needs_starship_init" == "true" ]]; then
            cat >> "$zshrc" <<'ZSHEOF'

# Starship prompt
if (( $+commands[starship] )); then
    eval "$(starship init zsh)"
fi
ZSHEOF
            log_success "Starship init added to ~/.zshrc"
        else
            log_success "Starship already configured in Zsh"
        fi
    fi

    # Ensure update alias is present
    if ! grep -q "alias update=" "$zshrc"; then
        printf '\n# System update\n%s\n' "$ZSH_UPDATE_ALIAS" >> "$zshrc"
        log_success "Update alias added to ~/.zshrc"
    fi

    # Fish-like autosuggestions and syntax highlighting (Fedora packages). Appended last:
    # zsh-syntax-highlighting must be sourced at the end of ~/.zshrc
    local zsh_plugins=""
    if ! grep -q 'zsh-autosuggestions' "$zshrc"; then
        zsh_plugins+="[[ -r $ZSH_AUTOSUGGESTIONS ]] && source $ZSH_AUTOSUGGESTIONS"$'\n'
    fi
    if ! grep -q 'zsh-syntax-highlighting' "$zshrc"; then
        zsh_plugins+="[[ -r $ZSH_SYNTAX_HIGHLIGHTING ]] && source $ZSH_SYNTAX_HIGHLIGHTING"$'\n'
    fi
    if [[ -n "$zsh_plugins" ]]; then
        printf '\n# Autosuggestions and syntax highlighting (keep at the end of ~/.zshrc)\n%s' "$zsh_plugins" >> "$zshrc"
        log_success "Autosuggestions and syntax highlighting added to ~/.zshrc"
    else
        log_success "Autosuggestions and syntax highlighting already configured"
    fi

    # Set zsh as default shell
    local zsh_path
    local current_shell

    zsh_path="$(command -v zsh)"
    current_shell="$(getent passwd "$(id -un)" | cut -d: -f7 || echo "")"

    # Ensure zsh is in /etc/shells
    if ! grep -qx "$zsh_path" /etc/shells; then
        echo "$zsh_path" | sudo tee -a /etc/shells >> "$LOG_FILE" 2>&1
        log_success "Zsh added to /etc/shells"
    fi

    if [[ "$current_shell" != "$zsh_path" ]]; then
        log "Changing default shell to Zsh..."
        if chsh -s "$zsh_path" 2>&1 | tee -a "$LOG_FILE"; then
            log_success "Default shell changed to Zsh (re-login to apply)"
        else
            log_error "Failed to change default shell"
        fi
    else
        log_success "Zsh already set as default shell"
    fi
}

